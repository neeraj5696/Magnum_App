import AsyncStorage from "@react-native-async-storage/async-storage";
import nacl from "tweetnacl";

export interface LicenseData {
  client: string;
  issuedAt: string;
  expiryDate: string; // Format: YYYY-MM-DD
}

export interface LicenseFile {
  data: LicenseData;
  signature: string; // Base64 Ed25519 signature
}

export type LicenseStatus =
  | "VALID"
  | "EXPIRED"
  | "TAMPERED"
  | "MISSING"
  | "INVALID_FORMAT";

export interface LicenseValidationResult {
  isValid: boolean;
  status: LicenseStatus;
  message: string;
  data?: LicenseData;
  daysRemaining?: number;
}

/**
 * Storage key used to persist the license in AsyncStorage
 */
const ASYNC_STORAGE_LICENSE_KEY = "@magnum_app_license_key";

/**
 * Public verification key (Base64 raw 32-byte Ed25519 key).
 * Generated by license-generator/generate-keys.js.
 * This public key can safely exist in the app code.
 */
export const APP_PUBLIC_KEY = "xVKJ+G9FnWpJaQUrVH7PEdBzkvGGZj2TjURwoB/uMFk=";

/**
 * Helper to decode Base64 string to Uint8Array
 */
function decodeBase64(base64: string): Uint8Array {
  if (typeof atob === "function") {
    const binary = atob(base64.trim());
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes;
  }

  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  const cleanBase64 = base64.replace(/=+$/, "");
  let bufferLength = (cleanBase64.length * 3) / 4;
  let bytes = new Uint8Array(bufferLength | 0);
  let p = 0;

  for (let i = 0; i < cleanBase64.length; i += 4) {
    const enc1 = chars.indexOf(cleanBase64.charAt(i));
    const enc2 = chars.indexOf(cleanBase64.charAt(i + 1));
    const enc3 = chars.indexOf(cleanBase64.charAt(i + 2));
    const enc4 = chars.indexOf(cleanBase64.charAt(i + 3));

    const chr1 = (enc1 << 2) | (enc2 >> 4);
    const chr2 = ((enc2 & 15) << 4) | (enc3 >> 2);
    const chr3 = ((enc3 & 3) << 6) | enc4;

    bytes[p++] = chr1;
    if (enc3 !== -1) bytes[p++] = chr2;
    if (enc4 !== -1) bytes[p++] = chr3;
  }
  return bytes;
}

/**
 * Helper to convert UTF-8 string to Uint8Array
 */
function encodeUtf8(str: string): Uint8Array {
  if (typeof TextEncoder !== "undefined") {
    return new TextEncoder().encode(str);
  }
  const utf8: number[] = [];
  for (let i = 0; i < str.length; i++) {
    let charcode = str.charCodeAt(i);
    if (charcode < 0x80) utf8.push(charcode);
    else if (charcode < 0x800) {
      utf8.push(0xc0 | (charcode >> 6), 0x80 | (charcode & 0x3f));
    } else if (charcode < 0xd800 || charcode >= 0xe000) {
      utf8.push(
        0xe0 | (charcode >> 12),
        0x80 | ((charcode >> 6) & 0x3f),
        0x80 | (charcode & 0x3f)
      );
    } else {
      i++;
      charcode = 0x10000 + (((charcode & 0x3ff) << 10) | (str.charCodeAt(i) & 0x3ff));
      utf8.push(
        0xf0 | (charcode >> 18),
        0x80 | ((charcode >> 12) & 0x3f),
        0x80 | ((charcode >> 6) & 0x3f),
        0x80 | (charcode & 0x3f)
      );
    }
  }
  return new Uint8Array(utf8);
}

/**
 * Core validation logic:
 * Checks signature authenticity using the Public Key, then verifies date validity.
 */
export function verifyLicense(
  licenseInput: string | LicenseFile,
  publicKeyBase64: string = APP_PUBLIC_KEY
): LicenseValidationResult {
  try {
    let license: LicenseFile;

    if (typeof licenseInput === "string") {
      license = JSON.parse(licenseInput.trim());
    } else {
      license = licenseInput;
    }

    if (!license || !license.data || !license.signature) {
      return {
        isValid: false,
        status: "INVALID_FORMAT",
        message: "Invalid license format. Expected { data, signature }."
      };
    }

    const { data, signature } = license;

    if (!data.expiryDate || !/^\d{4}-\d{2}-\d{2}$/.test(data.expiryDate)) {
      return {
        isValid: false,
        status: "INVALID_FORMAT",
        message: "Invalid expiry date format. Expected YYYY-MM-DD."
      };
    }

    // 1. Verify cryptographic signature with the Public Key
    const messageBytes = encodeUtf8(JSON.stringify(data));
    const signatureBytes = decodeBase64(signature);
    const publicKeyBytes = decodeBase64(publicKeyBase64);

    const isSignatureValid = nacl.sign.detached.verify(
      messageBytes,
      signatureBytes,
      publicKeyBytes
    );

    if (!isSignatureValid) {
      return {
        isValid: false,
        status: "TAMPERED",
        message: "License signature is invalid! The license has been altered or tampered with."
      };
    }

    // 2. Check date expiry
    const todayStr = new Date().toISOString().split("T")[0];
    const today = new Date(todayStr).getTime();
    const expiry = new Date(data.expiryDate).getTime();

    const diffDays = Math.ceil((expiry - today) / (1000 * 60 * 60 * 24));

    if (today > expiry) {
      return {
        isValid: false,
        status: "EXPIRED",
        message: `License expired on ${data.expiryDate}. Please renew.`,
        data,
        daysRemaining: diffDays
      };
    }

    return {
      isValid: true,
      status: "VALID",
      message: `License is active until ${data.expiryDate}.`,
      data,
      daysRemaining: diffDays
    };
  } catch (err: any) {
    return {
      isValid: false,
      status: "INVALID_FORMAT",
      message: err?.message || "Failed to parse license file."
    };
  }
}

/**
 * Save a license string to AsyncStorage after validating it
 */
export async function saveLicense(licenseContent: string): Promise<LicenseValidationResult> {
  const result = verifyLicense(licenseContent);
  if (!result.isValid) {
    return result;
  }
  await AsyncStorage.setItem(ASYNC_STORAGE_LICENSE_KEY, licenseContent.trim());
  return result;
}

/**
 * Load the currently stored license from AsyncStorage
 */
export async function loadStoredLicense(): Promise<string | null> {
  return await AsyncStorage.getItem(ASYNC_STORAGE_LICENSE_KEY);
}

// Import bundled default license from assets/license.json
let defaultBundledLicense: LicenseFile | null = null;
try {
  defaultBundledLicense = require("../assets/license.json");
} catch {
  defaultBundledLicense = null;
}

/**
 * Check the validity of the currently installed license.
 * Priority:
 * 1. Checks AsyncStorage (if client updated/activated a new license key)
 * 2. Falls back to the bundled assets/license.json
 */
export async function checkAppLicense(): Promise<LicenseValidationResult> {
  const stored = await loadStoredLicense();
  if (stored) {
    return verifyLicense(stored);
  }

  // Fallback to bundled license in assets/
  if (defaultBundledLicense) {
    return verifyLicense(defaultBundledLicense);
  }

  return {
    isValid: false,
    status: "MISSING",
    message: "No license installed or bundled with this app."
  };
}

/**
 * Check the validity of the currently installed license in AsyncStorage
 */
export async function checkStoredLicense(): Promise<LicenseValidationResult> {
  return checkAppLicense();
}

/**
 * Remove stored license from AsyncStorage (e.g. for reset / re-licensing)
 */
export async function removeStoredLicense(): Promise<void> {
  await AsyncStorage.removeItem(ASYNC_STORAGE_LICENSE_KEY);
}
